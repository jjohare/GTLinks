#!/usr/bin/env python3
"""Write web/public/assets/manifest.json: every car and prop GLB with node names, origin convention,
bounding box and triangle count, measured from the files themselves (GLB JSON chunk).

  python3 assets/src/manifest.py
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
import validate as V

ROOT = V.ROOT
ASSETS = os.path.join(ROOT, 'web/public/assets')

ORIGIN_NOTES = {
    'lodge': 'terrace centre; terrace surface at y=0; chalet behind (-Z), faces +Z',
    'chairlift_pylon': 'base centre on the ground; cable runs along Z',
    'chair': 'cable grip; hanger hangs down -Y so it can swing',
    'ramp': 'centre of the low leading edge on the ground; x in [-0.5,0.5], z in [0,1], height 1 at z=1 (scale in the front end)',
    'footbridge': 'start of span, centre of the deck surface (deck top y=0); unit 1 m along +Z, instance or scale in Z',
    'stein': 'base centre; handle on +X',
    'spectator': 'between the feet on the ground; faces +Z',
    'golfer': 'between the feet on the ground; faces +Z',
    'flag': 'base of the pin on the ground',
    'helicopter': 'fuselage centre; nose +Z, up +Y, left +X; rotor_main origin on the mast axis (spins about Y), rotor_tail origin at its hub (spins about X)',
    'golf_club': 'grip end',
    'drone': 'body centre; rotor_* origins at the rotor hubs',
}


def describe(path, kind, extra=None):
    js, b, size = V.load_glb(path)
    A = V.analyse(js)
    names = [n.get('name', '') for n in js['nodes']]
    roots = [js['nodes'][i].get('name') for i in js['scenes'][js.get('scene', 0)]['nodes']]
    lo, hi = A['bbox_min'], A['bbox_max']
    key = os.path.basename(path)[:-4]
    base0 = abs(lo[1]) < 0.02
    ctr_xz = ((lo[0] + hi[0]) / 2, (lo[2] + hi[2]) / 2)
    note = ORIGIN_NOTES.get(key)
    if note is None:
        if kind == 'car':
            note = 'on the ground, centred between the axles; faces +Z, +X is the car left; wheel_* origins at wheel centres'
        elif base0:
            note = 'base: origin on the ground (min y = 0)'
        else:
            note = 'see bbox'
    return dict(
        file=os.path.relpath(path, ASSETS), bytes=size, triangles=A['tris'],
        roots=roots, nodes=names, materials=sorted({m.get('name', '') for m in js.get('materials', [])}),
        bbox_min=[round(v, 4) for v in lo], bbox_max=[round(v, 4) for v in hi],
        size=[round(hi[k] - lo[k], 4) for k in range(3)], origin=note,
        node_positions={n: A['pos'][n] for n in names if n in A['pos'] and n not in ('',)} if kind == 'car' or key in ('helicopter', 'drone', 'chair') else None,
        extensions_used=js.get('extensionsUsed', []))


def main():
    out = dict(
        schema=1,
        note='Generated by assets/src/manifest.py from the GLB files. Metres, +Y up, objects face +Z, +X is left. Plain GLB: no Draco/meshopt/KTX/WebP.',
        cars={}, props={})
    cdir, pdir = os.path.join(ASSETS, 'cars'), os.path.join(ASSETS, 'props')
    for f in sorted(os.listdir(cdir)):
        if f.endswith('.glb'):
            out['cars'][f[:-4]] = describe(os.path.join(cdir, f), 'car')
    for f in sorted(os.listdir(pdir)):
        if f.endswith('.glb'):
            out['props'][f[:-4]] = describe(os.path.join(pdir, f), 'prop')
    out['totals'] = dict(files=len(out['cars']) + len(out['props']),
                         bytes=sum(v['bytes'] for g in ('cars', 'props') for v in out[g].values()))
    with open(os.path.join(ASSETS, 'manifest.json'), 'w') as fh:
        json.dump(out, fh, indent=1)
    print('manifest: %d cars, %d props, %d bytes total' % (len(out['cars']), len(out['props']), out['totals']['bytes']))


if __name__ == '__main__':
    main()
